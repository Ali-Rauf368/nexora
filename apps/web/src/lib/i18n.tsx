export type TKey = keyof typeof dict;
type Vars = Record<string, string | number>;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey, vars?: Vars) => string;
}

const I18nContext = createContext<I18n | null>(null);

export function translate(lang: Lang, key: TKey, vars?: Vars) {
  const s: string = dict[key][lang === "de" ? 0 : 1];
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : s;
}

export function I18nProvider({ children, initial }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (initial) return initial;
    try {
      return (localStorage.getItem("nexora.lang") as Lang) || "en";
    } catch {
      return "en";
    }
  });
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    document.documentElement.lang = l;
    try {
      localStorage.setItem("nexora.lang", l);
    } catch {
      /* private mode */
    }
  }, []);
  const value = useMemo(() => ({ lang, setLang, t: (key: TKey, vars?: Vars) => translate(lang, key, vars) }), [lang, setLang]);
  return <I18nContext value={value}>{children}</I18nContext>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
